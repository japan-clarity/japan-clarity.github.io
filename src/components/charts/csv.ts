import type { ChartSpec, SourceRecord } from "@/lib/research/types";
import type { Locale } from "@/lib/i18n/locales";

/**
 * CSV export with a full attribution header — required before redistributing
 * derived data (World Bank series are CC BY 4.0; Japanese government series
 * are reproduced with source attribution under their terms of use).
 */
export function buildCsv(
  spec: ChartSpec,
  locale: Locale,
  sources: SourceRecord[],
  accessDate: string,
): string {
  const lines: string[] = [];
  lines.push(`# ${spec.title[locale]}`);
  lines.push(`# Unit: ${spec.unit[locale]}`);
  for (const s of sources) {
    lines.push(`# Source: ${s.organization[locale]} — ${s.originalTitle}`);
    lines.push(`# URL: ${s.url}`);
    lines.push(`# License: ${s.license[locale]}`);
    lines.push(`# Reference period: ${s.referencePeriod}; accessed ${accessDate}`);
  }
  lines.push("# Generated by Japan Clarity (https://github.com/japan-clarity/japan-clarity.github.io)");
  lines.push("# Values are as published by the source; null (empty) = not published.");

  const header = [
    spec.categories ? "category" : "year",
    ...spec.series.map((s) => s.name[locale]),
  ];
  lines.push(header.join(","));

  spec.years.forEach((y, i) => {
    const label = spec.categories && spec.categories[i]
      ? spec.categories[i][locale]
      : String(y);
    const row = [label, ...spec.series.map((s) => (s.values[i] === null ? "" : String(s.values[i])))];
    lines.push(row.join(","));
  });
  return lines.join("\n") + "\n";
}

/** Trigger a client-side CSV download for the given spec. */
export function downloadCsv(
  spec: ChartSpec,
  locale: Locale,
  sources: SourceRecord[],
  accessDate: string,
) {
  const csv = buildCsv(spec, locale, sources, accessDate);
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${spec.id}.csv`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

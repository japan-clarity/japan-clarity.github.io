/**
 * Japan Clarity — Chapter 02 data code generation.
 *
 * Reads research/chapter02/notes/extracted-series.json (produced by
 * research/chapter02/scripts/extract-series.py with anchor validation against
 * the archived raw official documents) and generates
 * src/chapters/chapter-02/data.ts.
 *
 * Unit conventions (documented so validate-research.ts can mirror them):
 *  - GDP / household disposable income: source 十億円 → emitted 兆円 (÷1000, 1 dp)
 *  - wage indices: as extracted (2 dp, 2020年平均=100 growth-chain)
 *  - industry/employment shares: % of 経済活動計 / total employed (2 dp)
 *  - R&D 対GDP比: % as published (2 dp)
 *  - OECD GDP per hour worked: USD PPP, 2 dp; WB per-capita PPP: int$, int
 *
 * Usage: bun run scripts/generate-chapter-02-data.ts
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const sourcePath = resolve(ROOT, "research/chapter02/notes/extracted-series.json");
const targetPath = resolve(ROOT, "src/chapters/chapter-02/data.ts");

const series = JSON.parse(readFileSync(sourcePath, "utf-8")) as Record<string, any>;
const hash = createHash("sha256").update(readFileSync(sourcePath)).digest("hex").slice(0, 16);

const fmt = (v: unknown) =>
  v === null || v === undefined ? "null" : JSON.stringify(v);

function pairs(map: Record<string, number | null>, transform?: (v: number) => number): string {
  const entries = Object.entries(map)
    .map(([year, v]) => [Number(year), v === null ? null : transform ? transform(v) : v] as const)
    .sort((a, b) => a[0] - b[0]);
  return `[\n${entries.map(([y, v]) => `  [${y}, ${fmt(v)}],`).join("\n")}\n]`;
}

const tril = (v: number) => Math.round(v / 100) / 10; // 十億円 → 兆円 (1 dp)
const r2 = (v: number) => Math.round(v * 100) / 100;
const r1 = (v: number) => Math.round(v * 10) / 10;

const esri = series.esri;
const mhlw = series.mhlw.wages;
const oecd = series.oecd;
const wb = series.wb;
const rd = series.rd;

// ---- OECD / World Bank comparison tables (latest common year) -------------

const OECD_NAME_JA: Record<string, string> = {
  JPN: "日本", KOR: "韓国", NZL: "ニュージーランド", CAN: "カナダ", ITA: "イタリア",
  GBR: "イギリス", AUS: "オーストラリア", FRA: "フランス", SWE: "スウェーデン",
  DEU: "ドイツ", USA: "アメリカ", NLD: "オランダ",
};
const OECD_NAME_EN: Record<string, string> = {
  JPN: "Japan", KOR: "South Korea", NZL: "New Zealand", CAN: "Canada", ITA: "Italy",
  GBR: "United Kingdom", AUS: "Australia", FRA: "France", SWE: "Sweden",
  DEU: "Germany", USA: "United States", NLD: "Netherlands",
};
const WB_NAME_JA: Record<string, string> = {
  ...OECD_NAME_JA,
  SGP: "シンガポール",
};
const WB_NAME_EN: Record<string, string> = {
  ...OECD_NAME_EN,
  SGP: "Singapore",
};

const oecdYear = String(oecd.latestYear);
const oecdCompare = Object.entries(oecd.gdpPerHourCurrent as Record<string, Record<string, number>>)
  .map(([area, years]) => [area, r2(years[oecdYear])] as const)
  .filter(([, v]) => Number.isFinite(v))
  .sort((a, b) => a[1] - b[1]);

const wbYear = String(wb.compareLatestYear);
const wbCompare = Object.entries((wb.compare.gdpPerCapitaPpp as Record<string, Record<string, number>>))
  .map(([area, years]) => [area, Math.round(years[wbYear])] as const)
  .filter(([, v]) => Number.isFinite(v))
  .sort((a, b) => a[1] - b[1]);

function countryMap(names: Record<string, string>, areas: readonly string[]): string {
  return `{\n${areas.map((a) => `  ${a}: { ja: "${names[a]}", en: "${a === "JPN" ? "Japan" : names[a]}" },`).join("\n")}\n}`;
}
// English names differ from Japanese map values; build both maps explicitly.
function countryMapL10n(ja: Record<string, string>, en: Record<string, string>, areas: readonly string[]): string {
  return `{\n${areas.map((a) => `  ${a}: { ja: "${ja[a]}", en: "${en[a]}" },`).join("\n")}\n}`;
}

const OECD_AREAS = oecdCompare.map(([a]) => a);
const WB_AREAS = wbCompare.map(([a]) => a);

// ---- R&D ratio chain (2005–2024, two published windows) --------------------

const rdRatio: Record<string, number> = {};
for (const [y, v] of Object.entries(rd.older as Record<string, { ratioPct: number }>)) rdRatio[y] = v.ratioPct;
for (const [y, v] of Object.entries(rd.recent as Record<string, { ratioPct: number }>)) rdRatio[y] = v.ratioPct;

// ---- Emit -------------------------------------------------------------------

const out = `/**
 * Japan Clarity — Chapter 02 verified data series (Economy & Industry).
 *
 * GENERATED FILE — do not edit by hand.
 * Generated by scripts/generate-chapter-02-data.ts from
 * research/chapter02/notes/extracted-series.json
 * (extraction validated against archived raw official documents;
 *  see research/chapter02/notes/*.md for verbatim source quotes).
 *
 * Source snapshot sha256 (first 16 hex): ${hash}
 * Access/verification date: 2026-10-25.
 *
 * Pair arrays are [year, value]; null = value not published for that year.
 * Units: GDP & household income 兆円 (source 十億円 ÷ 1000); wage indices
 * 2020年平均=100 (growth-chain — see notes/mhlw-summary.md); shares are %;
 * OECD GDP per hour worked is current-price USD PPP; WB per-capita is
 * current int$ PPP.
 */

/** Nominal GDP (calendar year, 兆円) — ESRI 年次推計 2024, 1994–2024. 1994 = 521.7; 2024 = 634.2. */
export const GDP_NOMINAL_TRILLION: ReadonlyArray<[number, number | null]> = ${pairs(esri.gdp.nominal, tril)};

/** Real GDP (calendar year, 2020 chain-linked prices, 兆円) — ESRI. 1994 = 464.3; 2024 = 584.5. */
export const GDP_REAL_TRILLION: ReadonlyArray<[number, number | null]> = ${pairs(esri.gdp.real, tril)};

/** Real GDP growth (calendar year, %, published 対前年増加率) — ESRI. */
export const GDP_REAL_GROWTH: ReadonlyArray<[number, number | null]> = ${pairs(esri.gdp.realGrowth, r1)};

/** GDP deflator (calendar year, 2020暦年=100) — ESRI. 1994 = 112.4; 2024 = 108.5. */
export const GDP_DEFLATOR: ReadonlyArray<[number, number | null]> = ${pairs(esri.gdp.deflator, r1)};

/** Household sector net disposable income (calendar year, 兆円) — ESRI 家計勘定. */
export const HOUSEHOLD_DISPOSABLE_TRILLION: ReadonlyArray<[number, number | null]> = ${pairs(esri.household.netDisposableIncome, tril)};

/** Nominal wage index, 現金給与総額 調査産業計 (2020年平均=100, growth-chain) — MHLW MLS. */
export const WAGE_NOMINAL_INDEX: ReadonlyArray<[number, number | null]> = ${pairs(mhlw.nominalIndex)};

/** Real wage index (2020年平均=100, growth-chain; CPI 持家の帰属家賃を除く総合 deflated) — MHLW MLS. */
export const WAGE_REAL_INDEX: ReadonlyArray<[number, number | null]> = ${pairs(mhlw.realIndex)};

/** Real wage year-on-year change (%, as published by MHLW). */
export const WAGE_REAL_YOY: ReadonlyArray<[number, number | null]> = ${pairs(mhlw.realYoY, r1)};

/** Industry value-added share: 第一次産業 (% of 経済活動計, nominal) — ESRI s2n (derived grouping). */
export const INDUSTRY_VA_SHARE_PRIMARY: ReadonlyArray<[number, number | null]> = ${pairs(esri.industry.shares.primary, r2)};

/** Industry value-added share: 第二次産業 (% of 経済活動計) — ESRI s2n (derived grouping). */
export const INDUSTRY_VA_SHARE_SECONDARY: ReadonlyArray<[number, number | null]> = ${pairs(esri.industry.shares.secondary, r2)};

/** Industry value-added share: 第三次産業 (% of 経済活動計) — ESRI s2n (derived grouping). */
export const INDUSTRY_VA_SHARE_TERTIARY: ReadonlyArray<[number, number | null]> = ${pairs(esri.industry.shares.tertiary, r2)};

/** Manufacturing value-added share (% of 経済活動計) — ESRI s2n. 1994 = 23.4; 2024 = 19.0. */
export const INDUSTRY_VA_SHARE_MANUFACTURING: ReadonlyArray<[number, number | null]> = ${pairs(esri.industry.shares.manufacturing, r2)};

/** Employment share by sector (% of total employed, SNA activity basis) — ESRI s3 (derived grouping). */
export const EMPLOYMENT_SHARE_PRIMARY: ReadonlyArray<[number, number | null]> = ${pairs(esri.employment.shares.primary, r2)};
export const EMPLOYMENT_SHARE_SECONDARY: ReadonlyArray<[number, number | null]> = ${pairs(esri.employment.shares.secondary, r2)};
export const EMPLOYMENT_SHARE_TERTIARY: ReadonlyArray<[number, number | null]> = ${pairs(esri.employment.shares.tertiary, r2)};
export const EMPLOYMENT_SHARE_MANUFACTURING: ReadonlyArray<[number, number | null]> = ${pairs(esri.employment.shares.manufacturing, r2)};

/** Total employed persons (SNA activity basis, 万人) — ESRI s3. */
export const EMPLOYMENT_TOTAL: ReadonlyArray<[number, number | null]> = ${pairs(esri.employment.persons.total, r1)};
/** Manufacturing employed persons (万人) — ESRI s3. */
export const EMPLOYMENT_MANUFACTURING: ReadonlyArray<[number, number | null]> = ${pairs(esri.employment.persons.manufacturing, r1)};

/** R&D expenditure as % of GDP (fiscal years; 2005–2014 and 2015–2024 published windows) — 総務省 科学技術研究調査. */
export const RD_GDP_RATIO: ReadonlyArray<[number, number | null]> = ${pairs(rdRatio, r2)};

/** GDP per hour worked, current prices, USD PPP — OECD Productivity database (${oecdYear}). Ascending. */
export const OECD_GDP_HOUR_COMPARE: ReadonlyArray<[string, number]> = [\n${oecdCompare.map(([a, v]) => `  ["${a}", ${v}],`).join("\n")}\n];
export const OECD_COMPARE_YEAR = ${oecdYear};
export const OECD_COUNTRIES: Record<string, { ja: string; en: string }> = ${countryMapL10n(OECD_NAME_JA, OECD_NAME_EN, OECD_AREAS)};

/** Japan GDP per hour worked, chain-linked volume (2020=100), 1970–${oecdYear} — OECD. */
export const OECD_JPN_GDP_HOUR_VOLUME: ReadonlyArray<[number, number | null]> = ${pairs(oecd.gdpPerHourVolumeJpn, r1)};

/** Japan GDP per capita, current PPP int$ (WDI) — 1990–${wbYear}. */
export const WB_PC_JPN: ReadonlyArray<[number, number | null]> = ${pairs(wb.japan.gdpPerCapitaPpp, Math.round)};

/** GDP per capita, current PPP int$, ${wbYear} (WDI, 13 economies). Ascending. */
export const WB_PC_COMPARE: ReadonlyArray<[string, number]> = [\n${wbCompare.map(([a, v]) => `  ["${a}", ${v}],`).join("\n")}\n];
export const WB_COMPARE_YEAR = ${wbYear};
export const WB_COUNTRIES: Record<string, { ja: string; en: string }> = ${countryMapL10n(WB_NAME_JA, WB_NAME_EN, WB_AREAS)};

/** Real wage YoY for the latest 8 reported months (2026 Jan–Aug, 確報) — MHLW MLS. */
export const WAGE_MONTHLY_2026_REAL_YOY: ReadonlyArray<[number, number]> = [\n${Object.entries(mhlw.monthly2026 as Record<string, { realYoY: number }>).sort((a, b) => Number(a[0]) - Number(b[0])).map(([m, v]) => `  [${m}, ${r1(v.realYoY)}],`).join("\n")}\n];

export const DATA_SNAPSHOT_HASH = "${hash}";
`;

writeFileSync(targetPath, out, "utf-8");
console.log(`Wrote ${targetPath} (${out.length} bytes) from ${sourcePath}`);
console.log(`Snapshot hash: ${hash}`);
console.log(`OECD compare areas (${oecdYear}): ${oecdCompare.map(([a, v]) => `${a}=${v}`).join(" ")}`);
console.log(`WB compare areas (${wbYear}): ${wbCompare.map(([a, v]) => `${a}=${v}`).join(" ")}`);
